impl Params {
    /// Defaults, overridden by the JSON file named in MECH_PARAMS when present.
    pub fn load() -> Params {
        let base = Params::default();
        let Ok(path) = std::env::var("MECH_PARAMS") else { return base };
        let Ok(text) = std::fs::read_to_string(&path) else { return base };
        match serde_json::from_str::<Params>(&text) {
            Ok(p) => p,
            Err(e) => {
                crate::io::runtime::log(&format!("MECH_PARAMS ignored: {e}"));
                base
            }
        }
    }
}
